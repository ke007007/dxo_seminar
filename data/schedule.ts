//   ここを直すだけで、LPの「開催概要」と
//   DXO公式HPのイベントカードの両方に反映されます。
//   （曜日は日付から自動で計算されるので、書く必要はありません）
//
//   --------------------------------------------------------------------
//   ■ 書き方
//
//       { date: "2026-09-18", start: "13:00", end: "18:00" },
//
//       date  … 開催日　　年4ケタ - 月2ケタ - 日2ケタ
//       start … 開始時刻　24時間表記（午後1時なら 13:00）
//       end   … 終了時刻　24時間表記
//
//   --------------------------------------------------------------------
//   ■ 日程を追加する
//
//       下の一覧にある行をまるごとコピーして貼り付け、
//       日付と時刻を書き換えてください。
//       ※ 行の最後のカンマ「,」を消さないでください
//
//   ■ 終わった日程を消す
//
//       その行をまるごと削除してください。
//
//   ■「開催日程 調整中」と表示したい
//
//       日程の行を全部消して、[ ] だけの状態にしてください。
//       LPの表示が自動で「調整中」に切り替わります。
//
//   --------------------------------------------------------------------
//   ■ 補足を出したい（任意・使わなくてOK）
//
//       note: "残り1枠"  → 日付の右に赤字で表示されます
//       full: true       → 取り消し線＋「満員御礼」を表示します
//
//       例）{ date: "2026-09-18", start: "13:00", end: "18:00", full: true },
//
//   --------------------------------------------------------------------
//   もっと詳しい手順は「日程の変更方法.md」を見てください。
//   書き方を間違えた場合は公開が自動で止まるので、
//   おかしな日程がサイトに出てしまうことはありません。
// ==========================================================================

